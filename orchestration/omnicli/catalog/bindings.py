def _compact_payload(payload: list[dict]) -> list[dict]:
    """Lossless encoding of SPEC: short row keys and positional value arrays.

    Row keys are expanded once at module load; params/positionalSpecs are
    decoded back to their named shape inside _callTool's validation path. No
    metadata, value, or error message is lost — only source bytes.
    """
    for row in payload:
        row["params"] = {
            name: [value["flag"], value["type"]]
            for name, value in row["params"].items()
        }
        row["positionalSpecs"] = {
            name: [value["index"], value["required"], value["type"]]
            for name, value in row["positionalSpecs"].items()
        }
        for long, short in _SPEC_KEYS:
            row[short] = row.pop(long)
    return payload



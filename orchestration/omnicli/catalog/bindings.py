"""Generate the JavaScript bindings used by `omnicli exec`.

The bindings are deliberately thin at the transport layer: every call shells
out to the `omnicli` CLI, so a plan inherits the enable gate, field
projection, byte cap and disk buffer rather than reimplementing them. What the
sandbox buys is not a second policy engine — it is the ability to keep
intermediate values in variables instead of the model's context window.

The surface layer is not thin. Each catalogued tool gets one async function,
generated from its extracted `inputSchema`, so a plan calls `zoom({ url })` and
an unknown, missing or mistyped argument fails at the call site instead of
halfway through a fifty-call run. A companion `.d.ts` gives the model the same
contract as types, which is cheaper to read than the module itself.
"""


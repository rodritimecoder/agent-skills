#!/usr/bin/env python3
"""Generate the omnicli contract tree from the catalog's describe source.

The tree is a *derived artifact*: one markdown file per ENABLED tool, grouped
by skill. Each file carries the tool name, its when-to-use description, its
input schema, and one invocation example — all pulled from the same catalog
rows that power ``omnicli describe``. Nothing here is hand-authored.

Layout::

    contracts/INDEX.md              skill -> directory map
    contracts/<skill>/<tool>.md     one generated contract per enabled tool

Re-run this module after any catalog/policy change. Generated files are never
edited by hand (see references/contract-tree.md).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sqlite3
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
OMNICLI_DIR = HERE.parent
REPO_ROOT = OMNICLI_DIR.parent.parent
DEFAULT_ROOT = REPO_ROOT / "contracts"

# Marker embedded in every generated file. Used both for safety (only delete
# stale files that carry it) and as an invariant check.
GENERATED = "<!-- generated by contract_tree.py — DO NOT EDIT -->"

_UNSAFE = re.compile(r"[^A-Za-z0-9._-]+")
_TICKS = re.compile(r"`+")

# The describe payload builder is the single source of truth for contract
# shape. Reuse it when importable; the fallback mirrors it exactly from the
# same catalog columns so generation still works as a standalone script.
if str(OMNICLI_DIR) not in sys.path:
    sys.path.insert(0, str(OMNICLI_DIR))
try:
    from catalog import builder  # type: ignore
except ImportError as exc:  # pragma: no cover - broken install
    raise SystemExit(f"contract_tree: cannot import omnicli catalog: {exc}")

try:
    import omnicli as _omnicli  # type: ignore

    _describe = _omnicli._build_tool_contract
except Exception:  # pragma: no cover - fallback mirrors _build_tool_contract
    _describe = None


# ---------------------------------------------------------------------------
# catalog access
# ---------------------------------------------------------------------------

def open_catalog() -> sqlite3.Connection:
    """Open the built catalog without mutating it whenever possible.

    Read-only mode keeps regeneration deterministic: a second run reads the
    exact same bytes. If no catalog exists yet, build it once from the skill
    tree, then proceed as usual.
    """
    os.environ.setdefault("OMNICLI_DB_RO", "1")
    con = builder.connect()
    try:
        count = con.execute("SELECT count(*) FROM tools").fetchone()[0]
    except sqlite3.Error:
        count = 0
    if not count:
        os.environ.pop("OMNICLI_DB_RO", None)
        con = builder.connect()
        builder.ensure_built(con, progress=False)
    return con


def describe_payload(con: sqlite3.Connection, row: sqlite3.Row) -> dict[str, Any]:
    """Return the describe/contract payload for one tools row."""
    if _describe is not None:
        return _describe(con, row)
    contract = json.loads(row["contract"] or "{}")
    skill = con.execute(
        "SELECT aliases FROM skills WHERE name = ?", (row["skill"],)
    ).fetchone()
    return {
        "id": row["id"],
        "skill": row["skill"],
        "kind": row["kind"],
        "enabled": bool(row["enabled"]),
        "summary": row["summary"],
        "path": row["path"],
        "argv": json.loads(row["argv"] or "[]"),
        "aliases": json.loads(skill["aliases"] or "[]") if skill else [],
        "contract": contract,
    }


# ---------------------------------------------------------------------------
# rendering
# ---------------------------------------------------------------------------

def tool_filenames(payloads: list[dict[str, Any]]) -> dict[str, str]:
    """Map tool id -> safe markdown filename. Deterministic and collision-free."""
    # Files live at contracts/<skill>/<name>. Collisions only matter within
    # one skill directory, so scope the seen-set by skill.
    used: set[tuple[str, str]] = set()
    out: dict[str, str] = {}
    for payload in payloads:
        tid = payload["id"]
        skill = payload["skill"]
        # Inside contracts/<skill>/, drop the leading "<skill>/" so the
        # filename is just the tool's local name.
        prefix = skill + "/"
        local = tid[len(prefix):] if tid.startswith(prefix) else tid
        stem = _UNSAFE.sub("_", local).strip("_") or "tool"
        name = stem + ".md"
        if (skill, name) in used:
            digest = hashlib.sha1(tid.encode("utf-8")).hexdigest()[:8]
            name = f"{stem}-{digest}.md"
            while (skill, name) in used:
                digest = hashlib.sha1((tid + name).encode("utf-8")).hexdigest()[:8]
                name = f"{stem}-{digest}.md"
        used.add((skill, name))
        out[tid] = name
    return out


def _fence(text: str, lang: str = "") -> str:
    """Wrap text in a backtick fence long enough not to collide with content."""
    text = text.rstrip("\n")
    longest = max((len(m.group()) for m in _TICKS.finditer(text)), default=0)
    ticks = "`" * max(3, longest + 1)
    return f"{ticks}{lang}\n{text}\n{ticks}"


def build_example(payload: dict[str, Any]) -> str:
    """Derive one deterministic example invocation from the input schema."""
    cid = payload["id"]
    contract = payload.get("contract") or {}
    schema = contract.get("inputSchema") or {}
    props = schema.get("properties") or {}
    required = schema.get("required") or []
    if not isinstance(props, dict):
        props = {}
    if not isinstance(required, list):
        required = []

    parts = ["omnicli invoke", cid]
    for key in required:
        spec = props.get(key) or {}
        if not isinstance(spec, dict):
            spec = {}
        flag = spec.get("x-flag") or ("--" + str(key).replace("_", "-"))
        parts.append(str(flag))
        if spec.get("type") != "boolean":
            parts.append(f"<{key}>")

    if len(parts) == 2:
        flags = [f for f in (contract.get("flags") or []) if f not in ("--help", "-h")]
        positionals = contract.get("positionals") or []
        if flags:
            parts.append(str(flags[0]))
        elif positionals:
            parts.append("<positional>")
    return " ".join(parts)


def render_contract(payload: dict[str, Any]) -> str:
    """Render one contract markdown document."""
    contract = payload.get("contract") or {}
    schema = contract.get("inputSchema")
    if schema is None:
        schema = {}
    schema_json = json.dumps(
        schema, indent=2, ensure_ascii=False, sort_keys=True, default=str
    )
    description = (payload.get("summary") or "").strip()
    if not description:
        description = "No when-to-use description is recorded for this tool in the catalog."

    lines = [
        f"# {payload['id']}",
        "",
        GENERATED,
        "",
        "## Name",
        "",
        f"`{payload['id']}`",
        "",
        "## When to use",
        "",
        description,
        "",
        "## Input schema",
        "",
        _fence(schema_json, "json"),
        "",
        "## Example",
        "",
        _fence(build_example(payload), "bash"),
        "",
    ]
    return "\n".join(lines)


def render_index(groups: list[tuple[str, list[dict[str, Any]]]]) -> str:
    """Render the skill -> directory index."""
    total = sum(len(items) for _, items in groups)
    lines = [
        "# omnicli contract tree",
        "",
        GENERATED,
        "",
        "One generated contract per enabled tool, grouped by skill. Every",
        "file is produced by `contract_tree.py` from the omnicli catalog;",
        "never hand-edit anything under `contracts/`.",
        "",
        f"Enabled tools: {total} · Skills: {len(groups)}",
        "",
        "| Skill | Directory | Enabled tools |",
        "| --- | --- | --- |",
    ]
    for skill, items in groups:
        lines.append(f"| `{skill}` | [{skill}/]({skill}/) | {len(items)} |")
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# tree assembly / IO
# ---------------------------------------------------------------------------

def build_tree(root: Path) -> tuple[dict[Path, str], list[dict[str, Any]]]:
    """Build the in-memory tree: relative path -> rendered text, plus payloads."""
    con = open_catalog()
    try:
        rows = con.execute(
            "SELECT * FROM tools WHERE enabled = 1 ORDER BY id"
        ).fetchall()
        payloads = [describe_payload(con, row) for row in rows]
    finally:
        con.close()

    names = tool_filenames(payloads)
    by_skill: dict[str, list[dict[str, Any]]] = {}
    for payload in payloads:
        by_skill.setdefault(payload["skill"], []).append(payload)
    for items in by_skill.values():
        items.sort(key=lambda p: p["id"])

    files: dict[Path, str] = {}
    for payload in payloads:
        rel = Path(payload["skill"]) / names[payload["id"]]
        files[rel] = render_contract(payload)
    groups = [(skill, by_skill[skill]) for skill in sorted(by_skill)]
    files[Path("INDEX.md")] = render_index(groups)
    return files, payloads


def generated_md(root: Path) -> set[Path]:
    """All generated markdown files currently on disk under ``root``."""
    found: set[Path] = set()
    if not root.is_dir():
        return found
    for path in root.rglob("*.md"):
        try:
            with open(path, "r", encoding="utf-8") as fh:
                head = [next(fh, "") for _ in range(3)]
        except OSError:
            continue
        if any(GENERATED in line for line in head):
            found.add(path)
    return found


def write_tree(root: Path, files: dict[Path, str], clean: bool = True) -> None:
    """Write the tree atomically per file, pruning stale generated files."""
    root.mkdir(parents=True, exist_ok=True)
    expected = {root / rel for rel in files}

    if clean:
        for path in generated_md(root) - expected:
            path.unlink()
        for directory in sorted(
            (p for p in root.rglob("*") if p.is_dir()),
            key=lambda p: -len(p.parts),
        ):
            if not any(directory.iterdir()):
                directory.rmdir()

    for rel, text in files.items():
        dest = root / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        with open(dest, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)


def tree_digest(files: dict[Path, str]) -> str:
    """Deterministic sha256 over relative paths + bytes (for reproducibility)."""
    digest = hashlib.sha256()
    for rel in sorted(files, key=str):
        digest.update(str(rel).encode("utf-8"))
        digest.update(b"\0")
        digest.update(files[rel].encode("utf-8"))
        digest.update(b"\0")
    return digest.hexdigest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT,
                        help="output directory (default: <repo>/contracts)")
    parser.add_argument("--list", action="store_true",
                        help="print one enabled tool id per line and exit")
    parser.add_argument("--check", action="store_true",
                        help="verify on-disk bytes match generation; exit 1 on drift")
    parser.add_argument("--hash", action="store_true",
                        help="print deterministic sha256 of the generated tree and exit")
    parser.add_argument("--no-clean", action="store_true",
                        help="do not prune stale generated files")
    args = parser.parse_args(argv)

    files, payloads = build_tree(args.root)

    if args.list:
        for payload in payloads:
            print(payload["id"])
        return 0

    if args.hash:
        print(tree_digest(files))
        return 0

    if args.check:
        drift = [
            str(rel) for rel, text in files.items()
            if not (args.root / rel).is_file()
            or (args.root / rel).read_text(encoding="utf-8") != text
        ]
        stale = [str(p.relative_to(args.root)) for p in generated_md(args.root)
                 if p.relative_to(args.root) not in files]
        if drift or stale:
            print(f"contract tree DRIFT: {len(drift)} changed/missing, {len(stale)} stale")
            for item in drift[:20] + stale[:20]:
                print(f"  {item}")
            return 1
        print(f"contract tree OK: {len(payloads)} enabled tools, "
              f"{len(files) - 1} contract files + INDEX.md, sha256 {tree_digest(files)}")
        return 0

    write_tree(args.root, files, clean=not args.no_clean)
    skills = len({p["skill"] for p in payloads})
    print(f"contract tree generated: {len(payloads)} enabled tools across "
          f"{skills} skills -> {args.root} "
          f"({len(files) - 1} files + INDEX.md, sha256 {tree_digest(files)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

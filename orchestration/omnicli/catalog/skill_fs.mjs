// Read-only skills window for `omnicli exec` plans.
//
// vm_runner.mjs loads this module in the host process and exposes the returned
// API as the synthetic `omnicli_skills` module. It uses only node:fs and
// node:path, so a plan can browse skill guidance without a bridge round-trip,
// a child process, or a network call:
//
//   import { lsSkills, readSkill, readResource } from "omnicli_skills";
//   const skills = lsSkills();                      // [{name, description}, ...]
//   const body = readSkill("llama-build");          // full SKILL.md
//   const ctx = readResource("llama-build", "CONTEXT.md");
//
// The index comes from a manifest generated by exec_runner.py (via the same
// registry that builds the catalog), so zero-tool skills are included. Every
// read is confined to the skill's directory inside the manifest root.

import fs from "node:fs";
import path from "node:path";

const SKILL_MD = "SKILL.md";

const TRIGGER_MAX = 120;

/**
 * One-line, <=120-char routing trigger derived from a description.
 *
 * Prefer the first "when-to-use" sentence — that is the line a router actually
 * needs. Fall back to the first sentence. Both are collapsed to one line and
 * capped on a word boundary so a brief card stays a single bounded token.
 */
function deriveTrigger(description) {
  const text = String(description || "").replace(/\s+/g, " ").trim();
  if (!text) return "";
  const sentences = text.match(/[^.!?]+(?:[.!?]+|$)/g) || [text];
  const when = sentences.find((s) => /\buse (?:this skill )?when\b/i.test(s))
    || sentences.find((s) => /\bwhen the user\b/i.test(s))
    || sentences[0];
  const line = when.replace(/\s+/g, " ").trim();
  if (line.length <= TRIGGER_MAX) return line;
  const cut = line.slice(0, TRIGGER_MAX - 1).trimEnd();
  const lastSpace = cut.lastIndexOf(" ");
  return (lastSpace > 0 ? cut.slice(0, lastSpace) : cut) + "…";
}

/** Domain is the top-level directory the skill lives under in the manifest. */
function domainOf(dir) {
  const parts = String(dir || "").split(/[\\/]/).filter(Boolean);
  return parts.length > 1 ? parts[0] : "root";
}

/** Strictly lexical containment: no absolute paths, no `..`, no escape. */
function within(base, rel) {
  const value = rel == null || rel === "" ? "." : String(rel);
  if (value.split(/[\\/]/).includes("..")) {
    throw new Error(`omnicli_skills: '..' is not allowed in a resource path: ${value}`);
  }
  if (path.isAbsolute(value)) {
    throw new Error(`omnicli_skills: absolute resource paths are not allowed: ${value}`);
  }
  const target = path.resolve(base, value);
  const relative = path.relative(base, target);
  if (relative === ".." || relative.startsWith(".." + path.sep) || path.isAbsolute(relative)) {
    throw new Error(`omnicli_skills: path escapes the skill root: ${value}`);
  }
  return target;
}

/**
 * Build the skills API from a generated manifest.
 *
 * The manifest shape is `{ root, skills: [{ name, description, dir, root? }, ...] }`,
 * where `dir` is relative to `entry.root || manifest.root`. Nothing here opens
 * a socket or spawns a process; all reads go through node:fs against those roots only.
 */
export function createSkillFs(manifest) {
  const rawRoot = String((manifest && manifest.root) || "");
  const root = rawRoot ? path.resolve(rawRoot) : "";
  const skills = new Map();
  for (const entry of (manifest && manifest.skills) || []) {
    if (!entry || typeof entry.name !== "string" || !entry.name || !entry.dir) continue;
    const entryRoot = entry.root ? path.resolve(String(entry.root)) : root;
    skills.set(entry.name, {
      name: entry.name,
      description: String(entry.description || ""),
      dir: String(entry.dir),
      root: entryRoot,
    });
  }

  function skillBase(name) {
    const key = String(name);
    const entry = skills.get(key);
    if (!entry) {
      throw new Error(`omnicli_skills: unknown skill ${JSON.stringify(key)}`);
    }
    if (!entry.root) {
      throw new Error(`omnicli_skills: missing root for skill ${JSON.stringify(key)}`);
    }
    return within(entry.root, entry.dir);
  }

  /**
   * List the generated index.
   *
   * `lsSkills()` keeps the original full shape `[{name, description}, ...]`.
   * `lsSkills({brief:true})` returns compact routing cards
   * `[{name, domain, trigger}, ...]` — one line each, small enough to fit a
   * single bounded result. No other input changes full-mode behaviour.
   */
  function lsSkills(options) {
    const all = Array.from(skills.values());
    all.sort((a, b) => a.name.localeCompare(b.name));
    if (options && options.brief === true) {
      return all.map(({ name, description, dir }) => ({
        name,
        domain: domainOf(dir),
        trigger: deriveTrigger(description),
      }));
    }
    return all.map(({ name, description }) => ({ name, description }));
  }

  function readConfined(base, rel, { checkDir = false } = {}) {
    const target = within(base, rel);
    if (checkDir) {
      const stat = fs.statSync(target);
      if (stat.isDirectory()) {
        throw new Error(`omnicli_skills: ${String(rel)} is a directory, not a resource file`);
      }
    }
    // Symlinks inside a skill must not lead back out of its root either.
    let realBase = base;
    let realTarget = target;
    try {
      realBase = fs.realpathSync(base);
      realTarget = fs.realpathSync(target);
    } catch {
      // Missing/broken links surface as the original read error below.
    }
    const relative = path.relative(realBase, realTarget);
    if (relative === ".." || relative.startsWith(".." + path.sep) || path.isAbsolute(relative)) {
      throw new Error(`omnicli_skills: resource escapes the skill root: ${String(rel)}`);
    }
    return fs.readFileSync(target, "utf8");
  }

  /** The complete SKILL.md body for one skill. */
  function readSkill(name) {
    return readConfined(skillBase(name), SKILL_MD);
  }

  /** A file beneath the skill root (references/, assets/, scripts/, ...). */
  function readResource(name, rel) {
    return readConfined(skillBase(name), rel, { checkDir: true });
  }

  const api = { lsSkills, readSkill, readResource, skillsRoot: root };
  api.default = api;
  return api;
}

export default createSkillFs;

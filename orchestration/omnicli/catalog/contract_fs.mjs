// Sandbox-only filesystem view over the generated omnicli contract tree.
//
// An omnicli Code Mode exec plan can import this module directly — no host
// escape, no child processes, no network — and read contracts at progressive
// detail levels (the Anthropic `search_tools` "detail" idea, expressed as a
// filesystem read):
//
//   import { ls, read } from "./orchestration/omnicli/catalog/contract_fs.mjs";
//   const skills = ls();                          // ["academic-icm", ...]
//   const names  = ls("academic-icm");            // tool names in that skill
//   const name   = read("academic-icm/cli", "name");
//   const blurb  = read("academic-icm/cli", "name+description");
//   const full   = read("academic-icm/cli", "full");
//
// Uses only node:fs / node:path / node:url, all available inside vm_runner's
// sandbox. Paths are confined to the generated contracts/ directory.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const DETAIL_LEVELS = ["name", "name+description", "full"];

const GENERATED_MARKER = "generated by contract_tree.py";

function modulePath() {
  if (import.meta.filename) return import.meta.filename;
  if (typeof import.meta.url === "string" && import.meta.url.startsWith("file://")) {
    return fileURLToPath(import.meta.url);
  }
  throw new Error("contract_fs: cannot locate the module file via import.meta");
}

let _root;
export function contractsRoot() {
  if (_root) return _root;
  const override = process.env.OMNICLI_CONTRACTS_ROOT;
  if (override) {
    const candidate = path.resolve(override);
    if (!fs.existsSync(path.join(candidate, "INDEX.md"))) {
      throw new Error(`contract_fs: OMNICLI_CONTRACTS_ROOT has no INDEX.md: ${candidate}`);
    }
    _root = candidate;
    return _root;
  }

  // Resolve symlinks so an import through the repo-root `omnicli` shim still
  // walks up from the real orchestration/omnicli/catalog location.
  let dir = path.dirname(fs.realpathSync(modulePath()));
  while (true) {
    const candidate = path.join(dir, "contracts");
    if (fs.existsSync(path.join(candidate, "INDEX.md"))) {
      _root = candidate;
      return _root;
    }
    const parent = path.dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  throw new Error("contract_fs: could not locate contracts/INDEX.md above " + modulePath());
}

function resolveWithin(rel) {
  const root = contractsRoot();
  const target = path.resolve(root, rel == null || rel === "" ? "." : String(rel));
  const relative = path.relative(root, target);
  if (relative === ".." || relative.startsWith(".." + path.sep) || path.isAbsolute(relative)) {
    throw new Error(`contract_fs: path escapes contracts/: ${rel}`);
  }
  return target;
}

function normalizeFile(rel) {
  let target = resolveWithin(rel);
  try {
    const stat = fs.statSync(target);
    if (stat.isDirectory()) {
      throw new Error(
        `contract_fs: ${rel} is a directory — use ls(${JSON.stringify(rel)}) to list it`
      );
    }
  } catch (err) {
    if (err.code === "ENOENT" && !path.extname(target)) {
      target += ".md";
      fs.statSync(target); // rethrow a clean ENOENT if still missing
    } else {
      throw err;
    }
  }
  return target;
}

function section(text, heading) {
  // `m` makes ^ match line starts, but `$` would also match *line* ends —
  // use (?![\s\S]) for a true end-of-string assertion so the section isn't
  // truncated at its first newline.
  const re = new RegExp(
    "^## " + heading + "[^\\n]*\\n([\\s\\S]*?)(?=^## |(?![\\s\\S]))", "m"
  );
  const match = text.match(re);
  return match ? match[1].trim() : "";
}

function fenced(block) {
  const match = block.match(/^(`{3,})[^\n]*\n([\s\S]*?)^\1\s*$/m);
  return match ? match[2].trim() : block.trim();
}

function parseContract(text) {
  const nameLine = text.match(/^# (.+)$/m);
  const name = nameLine ? nameLine[1].trim() : "";
  const description = section(text, "When to use");
  const schemaText = fenced(section(text, "Input schema"));
  let inputSchema = schemaText;
  try {
    inputSchema = JSON.parse(schemaText);
  } catch {
    // Keep the raw text when a file does not carry a JSON schema.
  }
  const example = fenced(section(text, "Example"));
  return { name, description, inputSchema, example, raw: text };
}

/**
 * List names under a path in the contract tree (skills at the root, tool
 * names inside a skill). Sorted; file names lose their `.md` extension.
 */
export function ls(rel = ".") {
  const target = resolveWithin(rel);
  const stat = fs.statSync(target);
  if (!stat.isDirectory()) {
    return [path.basename(target, path.extname(target))];
  }
  return fs
    .readdirSync(target, { withFileTypes: true })
    .map((entry) =>
      entry.isDirectory()
        ? entry.name
        : entry.name.replace(/\.md$/, "")
    )
    .sort();
}

/**
 * Read one contract at a detail level: 'name', 'name+description', or
 * 'full'. Throws on an unknown level or a path outside the tree.
 */
export function read(rel, detail = "full") {
  if (!DETAIL_LEVELS.includes(detail)) {
    throw new Error(
      `contract_fs: unknown detail ${JSON.stringify(detail)}; expected one of ${DETAIL_LEVELS.join(", ")}`
    );
  }
  const target = normalizeFile(rel);
  const text = fs.readFileSync(target, "utf8");
  if (!text.includes(GENERATED_MARKER)) {
    throw new Error(`contract_fs: not a generated contract file: ${rel}`);
  }
  const parsed = parseContract(text);
  if (detail === "name") return parsed.name;
  if (detail === "name+description") {
    return { name: parsed.name, description: parsed.description };
  }
  return parsed;
}

export default { ls, read, contractsRoot, DETAIL_LEVELS };
